#!/usr/bin/env node
// Writes js/seeds-history.js: the fingerprint (js/seeds-version.js sceneFp) of every version of every built-in scene
// (js/seeds-scenes.js) in the repository's history, so the app can recognise an example room's untouched copy of an older
// scene and bring it up to date (main.js refreshSeedScenes). Run it after changing a flagship scene:
//   node tools/seed-history.mjs            (from the project folder; needs git)
// Every commit on any branch that touched js/seeds-scenes.js is read; each version is imported with the
// js/seeds-sources.js (and js/seeds-figures.js) of the same commit.
import { execSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const git = cmd => execSync('git ' + cmd, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 << 20, stdio: ['ignore', 'pipe', 'ignore'] });
const { sceneFp, sceneKey } = await import(pathToFileURL(join(ROOT, 'js/seeds-version.js')).href);
const scenes = mod => { const out = []; const add = d => { if (d && typeof d === 'object' && d.type && d.title && Array.isArray(d.bodies) && !out.includes(d)) out.push(d); }; Object.values(mod).forEach(v => Array.isArray(v) ? v.forEach(add) : add(v)); return out; };
const H = {}, LT = {}, put = d => { const k = sceneKey(d), f = sceneFp(JSON.parse(JSON.stringify(d))); (H[k] ||= []); if (!H[k].includes(f)) H[k].push(f); (LT[k] ||= new Set()); (d.lessons || []).forEach(l => l && l.title && LT[k].add(l.title)); };
const commits = git('log --all --format=%h -- js/seeds-scenes.js').trim().split('\n').filter(Boolean);
let n = 0;
for (const c of commits) {
  const dir = mkdtempSync(join(tmpdir(), 'seedhist-'));
  try {
    writeFileSync(join(dir, 'seeds-scenes.js'), git(`show ${c}:js/seeds-scenes.js`));
    for (const f of ['seeds-sources.js', 'seeds-figures.js']) { try { writeFileSync(join(dir, f), git(`show ${c}:js/${f}`)); } catch (e) { } }
    writeFileSync(join(dir, 'package.json'), '{"type":"module"}');
    const mod = await import(pathToFileURL(join(dir, 'seeds-scenes.js')).href);
    scenes(mod).forEach(put); n++;
  } catch (e) { console.warn(c, 'skipped:', e.message.split('\n')[0]); } finally { rmSync(dir, { recursive: true, force: true }); }
}
// the working copy too (it may be ahead of the last commit)
scenes(await import(pathToFileURL(join(ROOT, 'js/seeds-scenes.js')).href)).forEach(put);
const body = Object.keys(H).sort().map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(H[k])}`).join(',\n'), lbody = Object.keys(LT).sort().map(k => `  ${JSON.stringify(k)}: ${JSON.stringify([...LT[k]].sort())}`).join(',\n');
writeFileSync(join(ROOT, 'js/seeds-history.js'), `// Generated by tools/seed-history.mjs: fingerprints (js/seeds-version.js sceneFp) of every version of every built-in\n// scene in the repository's history. An example room's copy of a scene with one of these is an untouched seed copy.\nexport const SEED_HISTORY = {\n${body}\n};\n// every lesson title any version of the scene had: lessons whose titles are all here were never rewritten by the learner\nexport const SEED_LESSON_TITLES = {\n${lbody}\n};\n`);
console.log(`${n}/${commits.length} versions read; ${Object.keys(H).length} scenes, ${Object.values(H).reduce((a, v) => a + v.length, 0)} fingerprints → js/seeds-history.js`);
