// Seed versioning for the built-in scenes (the flagship dioramas of the example books).
//
// A book room stores its own copy of every diorama spec it shows (room:<bookId> in js/store.js), so a room seeded by an
// older version keeps that version's scene for ever: the copy, not js/seeds-scenes.js, is what opens. These helpers let
// main.js (App.refreshSeedScenes) tell an untouched old copy from one the learner has edited, and replace only the first.
//
//   sceneFp(spec)  a short fingerprint of what a scene IS (bodies, code, environment, camera, parameters ...), leaving
//                  out what the app migrates by itself or what records the learner's use of it: lessons, plan, levels,
//                  purpose, sources, slider values (values), edits (overrides, additions), and the stamp itself (seedFp).
//   isSeedCopy(d, key)  true when d is an unedited copy of some built-in version of the scene `key` (type|title): its
//                  fingerprint is the one stamped on it when it was written (seedFp), or one of the fingerprints of every
//                  version the repository ever shipped (SEED_HISTORY, generated by tools/seed-history.mjs), and it has
//                  no edits of its own (overrides, additions).
// Copies written from now on carry seedFp, so later changes to the seeds refresh them without regenerating the history.
import { SEED_HISTORY } from './seeds-history.js';

const SKIP = new Set(['lessons', 'plan', 'levels', 'purpose', 'sources', 'scale', 'tracks', 'values', 'overrides', 'ovV', 'additions', 'seedFp']);
// canonical JSON: object keys sorted, so the fingerprint does not depend on the order a migration wrote them in
function canon(v) {
  if (Array.isArray(v)) return '[' + v.map(canon).join(',') + ']';
  if (v && typeof v === 'object') return '{' + Object.keys(v).sort().filter(k => v[k] !== undefined).map(k => JSON.stringify(k) + ':' + canon(v[k])).join(',') + '}';
  return JSON.stringify(v === undefined ? null : v);
}
// cyrb53: a fast 53-bit string hash (public domain), written out in base 36
function hash(s) {
  let h1 = 0xdeadbeef, h2 = 0x41c6ce57;
  for (let i = 0; i < s.length; i++) { const c = s.charCodeAt(i); h1 = Math.imul(h1 ^ c, 2654435761); h2 = Math.imul(h2 ^ c, 1597334677); }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(36);
}
export function sceneFp(spec) {
  if (!spec || typeof spec !== 'object') return '';
  const o = {}; for (const k of Object.keys(spec)) if (!SKIP.has(k)) o[k] = spec[k];
  return hash(canon(o));
}
export const sceneKey = d => (d && d.type) + '|' + (d && d.title);
const edited = d => (d.overrides && Object.keys(d.overrides).length) || (Array.isArray(d.additions) && d.additions.length);
export function isSeedCopy(d, key = sceneKey(d)) {
  if (!d || edited(d)) return false;
  const fp = sceneFp(d);
  return fp === d.seedFp || (SEED_HISTORY[key] || []).includes(fp);
}
